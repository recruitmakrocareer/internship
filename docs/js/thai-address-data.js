function getThaiProvinces() {
  var seen = {};
  var result = [];
  for (var i = 0; i < THAI_ADDRESS_DB.length; i++) {
    var prov = THAI_ADDRESS_DB[i][2];
    if (!seen[prov]) { seen[prov] = true; result.push(prov); }
  }
  return result;
}

function getThaiDistricts(province) {
  var seen = {};
  var result = [];
  for (var i = 0; i < THAI_ADDRESS_DB.length; i++) {
    if (THAI_ADDRESS_DB[i][2] === province) {
      var dist = THAI_ADDRESS_DB[i][1];
      if (!seen[dist]) { seen[dist] = true; result.push(dist); }
    }
  }
  return result;
}

function getThaiSubdistricts(province, district) {
  var result = [];
  for (var i = 0; i < THAI_ADDRESS_DB.length; i++) {
    if (THAI_ADDRESS_DB[i][2] === province && THAI_ADDRESS_DB[i][1] === district) {
      result.push(THAI_ADDRESS_DB[i][0]);
    }
  }
  return result;
}

function getThaiPostcode(province, district, subdistrict) {
  for (var i = 0; i < THAI_ADDRESS_DB.length; i++) {
    if (THAI_ADDRESS_DB[i][2] === province && THAI_ADDRESS_DB[i][1] === district && THAI_ADDRESS_DB[i][0] === subdistrict) {
      return THAI_ADDRESS_DB[i][3];
    }
  }
  return '';
}
